// Regenerates src/lib/assistant/kb-data.ts from MDX. Runs on every build via `prebuild`.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SECTIONS = { projects: "projects", research: "research", writing: "writing" };

function cleanBody(raw) {
  return raw
    .split("\n")
    .filter((line) => !line.startsWith("import ") && line.trim() !== "")
    .join("\n")
    .replace(/export const metadata = \{[\s\S]*?\};/, "")
    .trim();
}

function splitSections(body) {
  const parts = body.split(/^## /m);
  const head = parts.shift().trim();
  const out = [];
  if (head) out.push({ heading: "", text: head });
  for (const part of parts) {
    const nl = part.indexOf("\n");
    out.push({ heading: part.slice(0, nl).trim(), text: part.slice(nl + 1).trim() });
  }
  return out.filter((s) => s.text.length > 0);
}

const chunks = [];
for (const [dir, routeBase] of Object.entries(SECTIONS)) {
  const dirPath = path.join(ROOT, "src", "content", dir);
  for (const file of readdirSync(dirPath).filter((f) => f.endsWith(".mdx"))) {
    const raw = readFileSync(path.join(dirPath, file), "utf8");
    const metaMatch = raw.match(/title:\s*"([^"]+?)"/);
    const slug = file.replace(/\.mdx$/, "");
    const title = metaMatch ? metaMatch[1] : slug;
    for (const s of splitSections(cleanBody(raw))) {
      chunks.push({ sourceRoute: `/${routeBase}/${slug}`, sourceTitle: title, heading: s.heading, text: s.text.slice(0, 1200) });
    }
  }
}

mkdirSync(path.join(ROOT, "src", "lib", "assistant"), { recursive: true });
writeFileSync(
  path.join(ROOT, "src", "lib", "assistant", "kb-data.ts"),
  `// GENERATED by scripts/build-kb.mjs — do not edit by hand.\nimport type { KbChunk } from "./kb";\n\nexport const KB_CHUNKS: KbChunk[] = ${JSON.stringify(chunks, null, 2)};\n`,
);
console.log(`wrote ${chunks.length} chunks`);
